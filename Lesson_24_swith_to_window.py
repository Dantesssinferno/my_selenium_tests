#
#
#
# Для переключения на новое окно нам потребуется следующий участок кода
#
# windows_2 = driver.window_handles[1]
#
# driver.switch_to.window(windows_1)
#
#
# Данный код Вам уже знаком, единственная разница в том, что мы создали новую переменную, которая своим названием
